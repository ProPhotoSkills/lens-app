const T: Partial<Record<Lang, Dict>> = { de, en };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Record<string, string | number>) => string };

const I18nContext = createContext<Ctx | null>(null);

function isLang(x: unknown): x is Lang {
  return typeof x === "string" && LANGS.some((l) => l.code === x);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("de");

  // Gespeicherte Wahl → sonst Sprache des Browsers → sonst Deutsch
  useEffect(() => {
    const saved = load<string | null>("ppsl_lang", null);
    if (isLang(saved)) return setLangState(saved);
    const nav = (navigator.language || "de").slice(0, 2);
    if (isLang(nav)) setLangState(nav);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    save("ppsl_lang", l);
  };

  // v6: In der Android-App gelten Ersatztexte (android-schalter.ts). Solange unklar ist, ob App oder Browser
  // (erster Aufbau), nehmen wir die App-Texte – so blitzt in der App nie „MemberAbo“ auf.
  const umgebung = useUmgebung();
  const appTexte = umgebung !== "browser";

  const t = (key: string, vars?: Record<string, string | number>) => {
    const ersatz = appTexte ? (APP_TEXTE[lang === "de" ? "de" : "en"][key] ?? undefined) : undefined;
    let s =
      ersatz && ANDROID_OHNE[ersatz.schalter]
        ? ersatz.text
        : (T[lang]?.[key] ?? (lang === "de" ? undefined : en[key]) ?? de[key] ?? key);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n außerhalb von I18nProvider");
  return c;
}
